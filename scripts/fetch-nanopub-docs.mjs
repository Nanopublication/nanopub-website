// Copies the Nanopublication Docs, which are published as nanopublications and
// edited in Nanodash, into docs/handbook/ as Markdown pages, one per topic.
//
// The docs are read through two published query templates: the table of
// contents of the docs resource, and the paragraphs of each topic. Both return
// only the newest version of each topic and paragraph that a member of the
// maintaining space published.
//
// Usage: node scripts/fetch-nanopub-docs.mjs [--if-missing]
//   --if-missing  do nothing if the pages are already there (for `yarn dev`)
//
// The pages are generated: don't edit them, edit the docs in Nanodash.

import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DOCS_RESOURCE = "https://w3id.org/spaces/nanopub/r/docs";
const API = "https://query.knowledgepixels.com/api";
const TOC_QUERY = "RA_QcFRTOjwYRz5Yw7d5uepH9RYhrmovFWUJ0kLsuMo_g/get-docs-topics";
const PARAGRAPHS_QUERY = "RAUm6gSQ7nTb6STnIfIHZa6WcMG0AEdyKv7BfhzaZZFlM/get-docs-paragraphs";
const NANODASH = "https://nanodash.knowledgepixels.com";

const OUT_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "docs", "handbook");
const MARKER = "<!-- Generated by scripts/fetch-nanopub-docs.mjs. Edit the docs in Nanodash, not here. -->";

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

// The query API rate-limits bursts (HTTP 429), so requests go one at a time,
// and a refused or failed one is retried after a pause.
async function query(template, params) {
  const url = `${API}/${template}?${new URLSearchParams(params)}`;
  for (let attempt = 1; ; attempt++) {
    let res;
    try {
      res = await fetch(url, { headers: { Accept: "application/json" }, signal: AbortSignal.timeout(60_000) });
    } catch (err) {
      if (attempt >= 4) throw new Error(`${url}: ${err.message}`);
      await sleep(2_000 * attempt);
      continue;
    }
    if (res.ok) {
      return (await res.json()).results.bindings.map((row) =>
        Object.fromEntries(Object.entries(row).map(([k, v]) => [k, v.value])),
      );
    }
    if (attempt >= 4 || !(res.status === 429 || res.status >= 500)) {
      throw new Error(`${url}: HTTP ${res.status}`);
    }
    const retryAfter = Number(res.headers.get("retry-after"));
    await sleep(retryAfter > 0 ? retryAfter * 1_000 : 2_000 * attempt);
  }
}

const nanodashPage = (iri) =>
  `${NANODASH}/part?${new URLSearchParams({ id: iri, context: DOCS_RESOURCE })}`;

const escapeHtml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// Backslash-escapes the characters that could start Markdown or HTML in a
// title, so that it is always read as plain text.
const escapeMarkdown = (s) => s.replace(/[\\`*_{}\[\]<>()#!|~&]/g, "\\$&");

const stripTags = (html) =>
  html
    .replace(/<[^>]*>/g, "")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim();

const ALLOWED_TAGS = new Set([
  "p", "br", "code", "pre", "strong", "b", "em", "i", "a", "ul", "ol", "li", "blockquote", "sub", "sup",
]);

// Paragraph content is HTML. Only the tags above are kept, and links only with
// an http(s), mailto or fragment URL. Other tags are dropped, their text kept,
// and any remaining angle bracket is escaped. Links relative to Nanodash, as
// its views write them, are made absolute.
function sanitize(html) {
  let out = "";
  let last = 0;
  for (const m of html.matchAll(/<(\/?)([a-zA-Z][a-zA-Z0-9]*)\b([^<>]*)>/g)) {
    out += html.slice(last, m.index).replace(/</g, "&lt;").replace(/>/g, "&gt;");
    last = m.index + m[0].length;
    const [, closing, rawTag, attrs] = m;
    const tag = rawTag.toLowerCase();
    if (!ALLOWED_TAGS.has(tag)) continue;
    if (closing) {
      out += `</${tag}>`;
    } else if (tag === "a") {
      const href = attrs.match(/\bhref\s*=\s*(?:"([^"]*)"|'([^']*)')/i);
      let url = href ? (href[1] ?? href[2]).trim() : "";
      if (url.startsWith("/") && !url.startsWith("//")) url = NANODASH + url;
      out += /^(https?:|mailto:|#)/i.test(url) ? `<a href="${url.replace(/"/g, "&quot;")}">` : "<a>";
    } else {
      out += tag === "br" ? "<br/>" : `<${tag}>`;
    }
  }
  out += html.slice(last).replace(/</g, "&lt;").replace(/>/g, "&gt;");
  // A blank line would end the raw HTML block that holds the content, and the
  // rest would then be read as Markdown.
  return out.replace(/\n\s*\n/g, "\n").trim();
}

function slugify(s) {
  return (
    s
      .normalize("NFKD")
      .replace(/[̀-ͯ]/g, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "") || "topic"
  );
}

const day = (dates) => dates.filter(Boolean).sort().at(-1)?.slice(0, 10);

// Front matter values are written as JSON strings, which YAML reads as
// double-quoted scalars.
function frontMatter(fields) {
  const lines = Object.entries(fields)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => {
      if (k === "last_update") return `last_update:\n  date: ${v}`;
      return `${k}: ${typeof v === "string" ? JSON.stringify(v) : v}`;
    });
  // The md format reads the page as CommonMark rather than MDX, so the HTML of
  // the paragraphs is passed through instead of being parsed as JSX, and braces
  // in it are not taken for expressions.
  return `---\n${lines.join("\n")}\nmdx:\n  format: md\n---\n\n${MARKER}`;
}

function topicPage(topic, paragraphs, position) {
  const parts = [
    frontMatter({
      title: topic.title,
      description: topic.description || undefined,
      sidebar_position: position,
      last_update: day(paragraphs.map((p) => p.date)),
    }),
  ];
  if (topic.description) {
    parts.push(`<p class="nanopub-docs-lead">${escapeHtml(topic.description)}</p>`);
  }
  for (const p of paragraphs) {
    parts.push(
      `## ${escapeMarkdown(p.title)}`,
      [
        `<div class="nanopub-docs-paragraph">`,
        sanitize(p.content),
        `<p class="nanopub-docs-source"><a href="${escapeHtml(p.np)}">Nanopublication</a> · <a href="${escapeHtml(nanodashPage(p.paragraph))}">Open in Nanodash</a></p>`,
        `</div>`,
      ].join("\n"),
    );
  }
  parts.push(
    `<p class="nanopub-docs-note">This page is a copy of the topic <a href="${escapeHtml(nanodashPage(topic.iri))}">${escapeHtml(topic.title)}</a> of the Nanopublication Docs. Each paragraph is a nanopublication. In Nanodash you also find their examples, related paragraphs, and version history, and members of the nanopub space can edit them there.</p>`,
  );
  return parts.join("\n\n") + "\n";
}

function indexPage(topics, total) {
  const items = topics.map(
    (t) =>
      `- [${escapeMarkdown(t.title)}](./${t.slug}.md)${t.description ? ` — ${escapeMarkdown(t.description)}` : ""}`,
  );
  return [
    frontMatter({
      title: "Handbook",
      sidebar_label: "Overview",
      sidebar_position: 0,
      description: "The complete guide to the nanopublication ecosystem, topic by topic.",
      last_update: day(topics.map((t) => t.lastUpdate)),
    }),
    `This handbook covers the nanopublication ecosystem topic by topic, from nanopublications themselves to identities and trust, spaces and roles, templates, queries, and views.`,
    `It is a copy of the [Nanopublication Docs](${DOCS_RESOURCE}), which are themselves published as nanopublications: each of its ${total} paragraphs is one. Members of the nanopub space write and edit them in Nanodash, and this website is updated from there.`,
    `## Topics`,
    items.join("\n"),
  ].join("\n\n") + "\n";
}

async function fetchDocs() {
  const toc = await query(TOC_QUERY, { resource: DOCS_RESOURCE });
  if (toc.length === 0) throw new Error("The table of contents is empty.");
  const topics = [];
  const slugs = new Set();
  for (const row of toc) {
    // The table of contents is shaped for a paragraph view: ?paragraph is the
    // topic, and ?content its description followed by the paragraph count.
    const description = stripTags(row.content.replace(/<p><em>\d+ paragraphs?<\/em><\/p>\s*$/, ""));
    let slug = slugify(row.title);
    for (let i = 2; slugs.has(slug); i++) slug = `${slugify(row.title)}-${i}`;
    slugs.add(slug);
    const paragraphs = await query(PARAGRAPHS_QUERY, { resource: row.paragraph, context: DOCS_RESOURCE });
    topics.push({ iri: row.paragraph, title: row.title, description, slug, paragraphs, lastUpdate: day(paragraphs.map((p) => p.date)) });
  }
  return topics;
}

// Refuses to clear the folder if it holds a page this script did not write.
async function clearOutDir() {
  if (!existsSync(OUT_DIR)) return;
  for (const name of await readdir(OUT_DIR)) {
    const file = path.join(OUT_DIR, name);
    if (!name.endsWith(".md") || !(await readFile(file, "utf8")).includes(MARKER)) {
      throw new Error(`${file} was not generated by this script; move it out of ${OUT_DIR} first.`);
    }
  }
  await rm(OUT_DIR, { recursive: true });
}

async function main() {
  if (process.argv.includes("--if-missing") && existsSync(path.join(OUT_DIR, "index.md"))) {
    console.log("Nanopublication Docs: already there, not fetching (run `yarn fetch-docs` to update).");
    return;
  }
  let topics;
  try {
    topics = await fetchDocs();
  } catch (err) {
    if (existsSync(path.join(OUT_DIR, "index.md"))) {
      console.warn(`Nanopublication Docs: fetching failed, keeping the pages from before.\n  ${err.message}`);
      return;
    }
    throw err;
  }
  await clearOutDir();
  await mkdir(OUT_DIR, { recursive: true });
  topics.forEach((t, i) => (t.page = topicPage(t, t.paragraphs, i + 1)));
  const total = topics.reduce((n, t) => n + t.paragraphs.length, 0);
  await writeFile(path.join(OUT_DIR, "index.md"), indexPage(topics, total));
  for (const t of topics) await writeFile(path.join(OUT_DIR, `${t.slug}.md`), t.page);
  console.log(`Nanopublication Docs: wrote ${topics.length} topics with ${total} paragraphs to docs/handbook/.`);
}

main().catch((err) => {
  console.error(`Nanopublication Docs: ${err.message}`);
  process.exit(1);
});
